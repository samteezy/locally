const MAX_ITERATIONS_DEFAULT = 10;

/**
 * Consulted when the model offers a final answer. Return text to push back as a user turn and keep
 * the loop running, or null to accept the answer.
 *
 * This is the only thing that lets a caller's "how widely to search" setting shape the run rather
 * than just flavour the prompt: a "very thorough" sweep that concluded after five iterations of a
 * twenty-iteration budget, having read fewer files than a "medium" one, is what issue #16 measured.
 * The `while` guard still bounds everything, so a policy that always wants more cannot run away.
 */
export type DraftAnswerHook = (draft: { text: string; iterations: number }) => string | null;

export async function runAgentLoop(
  config: ResolvedAgentConfig,
  messages: Message[],
  tools: AgentTool[],
  maxIterations: number = MAX_ITERATIONS_DEFAULT,
  onProgress?: (message: string) => void,
  signal?: AbortSignal,
  onDraftAnswer?: DraftAnswerHook
): Promise<AgentRunResult> {
  const startedAt = Date.now();
  const toolDefs: ToolDefinition[] = tools.map((t) => t.definition);
  const toolMap = new Map<string, AgentTool["handler"]>(
    tools.map((t) => [t.definition.function.name, t.handler])
  );

  let promptTokens = 0;
  let completionTokens = 0;

  // Cache keyed by "toolName:normalizedArgsJson" — return cached results on duplicate calls.
  // Normalized to avoid cache misses from semantically identical but whitespace-differing JSON.
  // Capped at MAX_CACHE_SIZE entries; evicts oldest when full.
  const MAX_CACHE_SIZE = 50;
  const toolResultCache = new Map<string, string>();

  /**
   * Run one tool call and return the text that goes back to the model.
   *
   * In-flight calls are tracked alongside finished ones so that two identical calls in the same
   * parallel batch collapse to a single execution rather than racing to fill the cache.
   */
  const inFlight = new Map<string, Promise<string>>();

  const dispatch = async (toolCall: ToolCall): Promise<string> => {
    const { name, arguments: argsJson } = toolCall.function;
    try {
      // Parsed once — used for cache key normalization and handler invocation.
      let parsedArgs: unknown;
      try {
        parsedArgs = JSON.parse(argsJson);
      } catch {
        throw new Error(`Invalid JSON in tool arguments: ${argsJson}`);
      }
      const cacheKey = `${name}:${JSON.stringify(parsedArgs)}`;

      const cached = toolResultCache.get(cacheKey);
      if (cached !== undefined) {
        // Still reported: from the caller's side a cache hit is activity, and a run that is
        // looping on one repeated call is exactly what a heartbeat should reveal.
        onProgress?.(`[tool: ${name}] ${argsJson} (cached)`);
        return `(already retrieved — returning cached result)\n${cached}`;
      }

      const pending = inFlight.get(cacheKey);
      if (pending) {
        onProgress?.(`[tool: ${name}] ${argsJson} (cached)`);
        return `(already retrieved — returning cached result)\n${await pending}`;
      }

      onProgress?.(`[tool: ${name}] ${argsJson}`);
      const handler = toolMap.get(name);
      if (!handler) return `Error: unknown tool "${name}"`;

      const run = handler(parsedArgs);
      inFlight.set(cacheKey, run);
      let result: string;
      try {
        result = await run;
      } finally {
        inFlight.delete(cacheKey);
      }

      if (toolResultCache.size >= MAX_CACHE_SIZE) {
        toolResultCache.delete(toolResultCache.keys().next().value!);
      }
      toolResultCache.set(cacheKey, result);
      return result;
    } catch (err) {
      return `Error: ${err instanceof Error ? err.message : String(err)}`;
    }
  };

  let iterations = 0;

  // On a completion failure, annotate the error with how far we got so the caller knows
  // whether any local work happened before the failure. Preserves the LocallyError category.
  const augmentProgress = (err: unknown): unknown => {
    if (err instanceof LocallyError && (iterations > 1 || completionTokens > 0)) {
      return new LocallyError(
        `${err.message} (failed after ${iterations} iteration(s), ${completionTokens} tokens generated locally so far)`,
        { category: err.category, origin: err.origin, retriable: err.retriable, fix: err.fix }
      );
    }
    return err;
  };

  // An in-flight completion is aborted by the merged signal inside the client, but tool calls
  // and cache hits run between completions — so the loop also checks at the top of each
  // iteration rather than only noticing on the next fetch.
  const throwIfCancelled = (): void => {
    if (!signal?.aborted) return;
    throw new LocallyError("Task cancelled by the caller.", {
      category: "cancelled",
      origin: "local",
      retriable: true,
      fix: "nothing to fix — re-run the task if the cancellation was not intended.",
    });
  };

  while (iterations < maxIterations) {
    throwIfCancelled();
    iterations++;
    onProgress?.(`[iteration ${iterations}/${maxIterations}]`);

    let turn;
    try {
      turn = await runCompletionWithTools(config, messages, toolDefs, signal);
    } catch (err) {
      throw augmentProgress(err);
    }
    promptTokens += turn.usage?.promptTokens ?? 0;
    completionTokens += turn.usage?.completionTokens ?? 0;

    // Push the full assistant turn (including tool_calls) before processing results.
    // The API requires the assistant message with tool_calls to precede role:"tool" messages.
    messages.push({
      role: "assistant",
      content: turn.content,
      ...(turn.tool_calls ? { tool_calls: turn.tool_calls } : {}),
    });

    if (!turn.tool_calls || turn.tool_calls.length === 0) {
      if (typeof turn.content !== "string") {
        throw new Error("Model returned neither tool calls nor text content.");
      }

      // Only worth asking with iterations left to spend: pushed at the cap, the answer would come
      // from the forced tool-less final call, where the model cannot act on what it was asked.
      const nudge = iterations < maxIterations ? onDraftAnswer?.({ text: turn.content, iterations }) : null;
      if (nudge) {
        onProgress?.("[keep sweeping]");
        messages.push({ role: "user", content: nudge });
        continue;
      }

      return {
        text: turn.content,
        model: config.model,
        promptTokens,
        completionTokens,
        iterations,
        durationMs: Date.now() - startedAt,
        cappedAtMaxIterations: false,
        filesRead: 0,
        filesReadPaths: [],
        filesMatchedPaths: [],
        filesListedPaths: [],
        nudged: false,
      };
    }

    // A turn's tool calls are independent by construction — the model asked for all of them
    // before seeing any result — so they run concurrently. Serially awaiting three or four
    // searches multiplied the wall clock of every iteration for nothing. Results are still
    // pushed in call order: the API requires each role:"tool" message to follow its call.
    const results = await Promise.all(turn.tool_calls.map((toolCall) => dispatch(toolCall)));

    for (let i = 0; i < turn.tool_calls.length; i++) {
      messages.push({
        role: "tool",
        tool_call_id: turn.tool_calls[i].id,
        content: results[i],
      });
    }
  }

  // Max iterations reached — call without tools to force a final text answer
  throwIfCancelled();
  let finalTurn;
  try {
    finalTurn = await runCompletionWithTools(config, messages, undefined, signal);
  } catch (err) {
    throw augmentProgress(err);
  }
  promptTokens += finalTurn.usage?.promptTokens ?? 0;
  completionTokens += finalTurn.usage?.completionTokens ?? 0;
  if (typeof finalTurn.content !== "string") {
    throw new LocallyError(
      `Agent exceeded ${maxIterations} iterations and the model returned no final content.`,
      {
        category: "constraint",
        origin: "local",
        retriable: true,
        fix: "raise \"max_iterations\" on the call, or narrow the task so the model finishes sooner.",
      }
    );
  }
  return {
    text: finalTurn.content,
    model: config.model,
    promptTokens,
    completionTokens,
    iterations: iterations + 1,
    durationMs: Date.now() - startedAt,
    cappedAtMaxIterations: true,
    filesRead: 0,
    filesReadPaths: [],
    filesMatchedPaths: [],
    filesListedPaths: [],
    nudged: false,
  };
}
