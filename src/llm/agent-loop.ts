/**
 * How a tool touches the filesystem — declared, not inferred from its name.
 *
 * runAgenticTask used to wrap tools in a `switch` over their names to apply the allowedRoots fence
 * and record what the run had seen, with a `default:` that returned the tool unwrapped. Renaming a
 * tool would therefore have silently dropped it out of the sandbox *and* out of the coverage note,
 * with no error anywhere. Declaring the contract on the tool makes that a type error instead.
 */
export interface ToolFence {
  /** The argument key holding the path this tool touches. Validated against allowedRoots. */
  pathKey: string;
  /** Whether the path must already exist (reads and searches) or may be created (writes). */
  mustExist: boolean;
  /** Fill in the task's own directory when the model omits the path, rather than erroring. */
  defaultsToTaskRoot?: boolean;
  /** What a successful call proves about the files it touched, for explore_task's coverage note. */
  evidence?: "read" | "searchHits" | "listing";
  /** Whether the config's `ignorePatterns` are merged into this tool's `ignore_patterns` argument. */
  mergesIgnorePatterns?: boolean;
}

export interface AgentTool {
  definition: ToolDefinition;
  handler: (args: unknown) => Promise<string>;
  fence: ToolFence;
}

export interface AgentRunResult {
  text: string;
  model: string;
  /** Tokens the local model processed (prompt/input) across all loop iterations. */
  promptTokens: number;
  /** Tokens generated by the local model across all loop iterations. */
  completionTokens: number;
  /** Number of completion calls made (loop iterations, plus a forced final call if capped). */
  iterations: number;
  /** Wall-clock time spent in the loop. */
  durationMs: number;
  /**
   * True when the loop ran out of iterations and the answer came from the forced final call
   * rather than the model deciding it was done. A run that stopped because it hit the budget
   * has a different reliability profile from one that stopped because it finished, and the
   * iteration count alone does not distinguish them (issue #13).
   */
  cappedAtMaxIterations: boolean;
  /**
   * Distinct files opened with read_file. Filled in by the caller that owns the tool handlers
   * (see runAgenticTask); the loop itself dispatches tools by name and does not inspect them.
   */
  filesRead: number;
  /**
   * Canonical paths of those files. The count alone cannot answer the question issue #16 asks —
   * which of the files this answer describes did the run never actually look at — so the
   * identities are carried, not just the tally.
   */
  filesReadPaths: string[];
  /** Canonical paths the model saw matching lines from, via an explore_files search. */
  filesMatchedPaths: string[];
  /** Canonical paths a directory listing named — the file's existence was seen, not its contents. */
  filesListedPaths: string[];
  /**
   * True when the run was asked to keep sweeping before its answer was accepted. Set by
   * runAgenticTask, which owns the sweep floor; the loop only knows it was handed a callback.
   */
  nudged: boolean;
}

